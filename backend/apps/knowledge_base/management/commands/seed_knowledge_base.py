class Command(BaseCommand):
    help = "بذرپاشی اولیه پایگاه دانش، قوانین و استانداردهای ملی و بین‌المللی HSE"

    def handle(self, *args, **options):
        created_count = 0
        updated_count = 0
        for data in SEED_SOURCES:
            code = data["code"]
            obj, created = KnowledgeSource.objects.update_or_create(
                code=code,
                organization=None,
                defaults=data,
            )
            if created:
                created_count += 1
            else:
                updated_count += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Seed completed: {created_count} sources created, {updated_count} updated."
            )
        )
